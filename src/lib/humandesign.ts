function digitSum(value: number): number {
  return String(Math.abs(value))
    .split("")
    .reduce((acc, ch) => acc + Number(ch), 0);
}

function parseDate(birthDate: string): { day: number; month: number; year: number } {
  const [y, m, d] = birthDate.split("-").map((part) => parseInt(part, 10));
  return {
    year: Number.isFinite(y) ? y : 1990,
    month: Number.isFinite(m) ? m : 1,
    day: Number.isFinite(d) ? d : 1,
  };
}

function parseHour(birthTime: string): number {
  const [h] = birthTime.split(":").map((part) => parseInt(part, 10));
  if (!Number.isFinite(h) || h < 0 || h > 23) return 12;
  return h;
}

export function calculateHD(
  name: string,
  birthDate: string,
  birthTime: string,
  birthPlace: string,
): HDResult {
  const { day, month, year } = parseDate(birthDate);
  const hour = parseHour(birthTime);

  // Тип
  let typeKey: HDTypeKey;
  if (day === month) {
    typeKey = "reflector";
  } else {
    const sum = digitSum(day) + digitSum(month) + digitSum(year);
    const bucket = sum % 5;
    if (bucket === 0 || bucket === 1) typeKey = "generator";
    else if (bucket === 2) typeKey = "manifesting-generator";
    else if (bucket === 3) typeKey = "projector";
    else typeKey = "manifestor";
  }

  // Профиль
  const profileCode = HOUR_TO_PROFILE[hour] ?? "1/3";

  // Авторитет
  const authorityKey = MONTH_TO_AUTHORITY[Math.min(Math.max(month, 1), 12) - 1] ?? "sacral";

  // Определение
  const definitionKey = day % 3 === 0 ? "single" : day % 3 === 1 ? "split" : "triple";

  const typeData = TYPES[typeKey];
  const profileData = PROFILES[profileCode];
  const authorityData = AUTHORITIES[authorityKey];

  // birthPlace и name не влияют на расчёт типа, но входят в состав отчёта
  void name;
  void birthPlace;

  return {
    type: typeKey,
    profile: profileCode,
    authority: authorityData.name,
    definition: DEFINITIONS[definitionKey],
    typeData,
    profileData,
    authorityData,
  };
}

/** Определённые центры бодиграфа для типа. */
export function getDefinedCenters(typeKey: HDTypeKey): CenterKey[] {
  return TYPES[typeKey].centers;
}

